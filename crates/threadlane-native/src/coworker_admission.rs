/// Exact automatic admission input. Embedded confirmation flags are excluded from the subject.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdmissionRequest {
    /// Stable idempotency key, never regenerated by recovery.
    pub request_key: String,
    /// Source job/ledger revisions and exact existing approval and capability request.
    pub binding: BindJobApprovalRequest,
    /// Exact current published planning result; automatic admission requires this linkage.
    pub planning_result: PlanningResultRef,
    /// Expected current brief digest.
    pub work_brief_digest: String,
    /// Controller consent fields. Its revision refers to the source job, before linkage.
    pub execution: FreezeControllerExecutionEnvelopeRequest,
    /// Exact Reviewer profile tier (`None` selects the explicit default).
    pub reviewer_difficulty: Option<Difficulty>,
    /// Exact Closure profile tier (`None` selects the explicit default).
    pub closure_difficulty: Option<Difficulty>,
}

impl AdmissionRequest {
    fn normalized(&self) -> Self {
        let mut request = self.clone();
        request.execution.operator_attested = false;
        request.execution.confirm_approval_subject_digest = None;
        request.execution.confirm_envelope_digest = None;
        request
    }

    fn validate(&self) -> Result<(), NativeError> {
        bounded(self)?;
        validate_bounded_identifier(
            &self.request_key,
            "admission.request_key",
            MAX_COWORKER_ID_LEN,
        )?;
        let b = &self.binding;
        let e = &self.execution;
        validate_bounded_identifier(&b.binding_id, "binding_id", MAX_COWORKER_ID_LEN)?;
        validate_bounded_identifier(&b.job_id, "job_id", MAX_COWORKER_ID_LEN)?;
        if b.expected_job_revision == 0
            || b.expected_ledger_revision.is_none()
            || b.controller_envelope.is_none()
            || b.binding_id != e.binding_id
            || b.thread_uuid != e.thread_uuid
            || b.job_id != e.job_id
            || b.expected_job_revision != e.expected_job_revision
            || b.policy != e.policy
        {
            return Err(invalid("Admission requires exact source revisions, identity, policy and explicit capabilities"));
        }
        self.planning_result.validate()?;
        Ok(())
    }
}

/// Canonical executable and exact provider/model choice frozen by admission.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdmissionExecutablePin {
    /// Exact normalized profile choice, including adapter and model/effort.
    pub choice: SelectedRoleChoice,
    /// Canonical executable path; consumers must use this path without PATH resolution.
    pub canonical_executable: PathBuf,
}

impl AdmissionExecutablePin {
    /// Returns the frozen canonical path after checking that it still names an executable.
    /// A missing path or a new symlink fails closed; there is no fallback resolution.
    pub fn executable(&self) -> Result<&Path, NativeError> {
        validate_absolute_no_symlink_components(
            &self.canonical_executable,
            "admission executable",
        )?;
        let validated = threadlane_workers::validate_executable_file(&self.canonical_executable)
            .map_err(|_| invalid("Frozen admission executable is unavailable"))?;
        if validated != self.canonical_executable {
            return Err(invalid("Frozen executable canonical identity drifted"));
        }
        Ok(&self.canonical_executable)
    }
}

