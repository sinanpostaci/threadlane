//! Trusted-local admission of an existing job, published planning result and exact approval.
//!
//! Lock order: admission lock -> workflow transaction (released) -> controller transaction
//! (released). Preparation and inspection take no locks. No workflow/controller callback may
//! acquire the admission lock. A durable intent precedes linkage; linkage and its immutable
//! marker share one workflow transaction. Reconciliation performs persistence only.
//!
//! A visible final receipt is not proof that its directory sync succeeded. Successful writers
//! retain a process-local durability witness. After restart, an effectful execution gate may sync an unchanged Complete receipt and its
//! existing ledgers to establish a fresh witness. Incomplete or explicitly Uncertain intents
//! require explicit reconciliation. Inspection never syncs, locks, or repairs state.

