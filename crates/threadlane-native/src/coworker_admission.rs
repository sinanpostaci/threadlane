/// Complete consent subject, constructed entirely in memory.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdmissionPreview {
    /// Supported admission schema (`1`).
    pub schema_version: u32,
    /// Original normalized request, with its original source revisions and timestamp.
    pub request: AdmissionRequest,
    /// Prospective workflow ledger revision after linkage and marker persistence.
    pub resulting_ledger_revision: u64,
    /// Prospective linked job, including resolved tasks, interfaces and capabilities.
    pub proposed_job: CoworkerJobRecord,
    /// Exact immutable authority subject being admitted.
    pub approval_subject_digest: String,
    /// Frozen authority concurrency cap (not inferred from role budgets).
    pub max_parallel: usize,
    /// Frozen authority execution/stream budgets.
    pub authority_budgets: ExecutionBudgets,
    /// Exact prospective controller execution envelope; attestation is false in previews.
    pub envelope: FrozenControllerExecutionEnvelope,
    /// Canonical provider executables included in consent.
    pub executable_pins: AdmissionExecutablePins,
    /// Current Orchestrator/Architect configuration under the separate recorded planning policy.
    /// Blocked roles include explicit unavailable/disabled reasons. This grants no new authority
    /// and does not claim that a configured role was historically invoked.
    pub planning_configuration: PreflightReport,
    /// Exact current profile configuration, including disabled assignments and difficulty tiers;
    /// configured planning choices remain separate from proven historical calls.
    pub planning_profile: threadlane_workflow::WorkflowProfile,
    /// Exact current model definitions for configured planning assignments, including blocked roles.
    pub planning_models: Vec<threadlane_workflow::ModelDefinition>,
    /// Exact tool definitions for those planning models; disabled tools remain visible.
    pub planning_tools: Vec<threadlane_workflow::ToolDefinition>,
    /// Existing validated planning authority with original policy, budgets and reservations.
    pub planning_authority: crate::coworker_workflow::PlanningAdviceGrant,
    /// Human-selected conversational Coworker has no profile execution slot.
    pub coworker_configuration: String,
    /// Domain-separated digest of every other field in this preview.
    pub preview_digest: String,
}

impl AdmissionPreview {
    /// Computes the admission subject without changing existing v1 authority/envelope digests.
    pub fn compute_digest(&self) -> Result<String, NativeError> {
        let mut subject = self.clone();
        subject.preview_digest.clear();
        subject.request = subject.request.normalized();
        subject.envelope.operator_attested = false;
        let bytes = bounded(&("threadlane-native:coworker-admission-preview:v1", subject))?;
        Ok(sha256_hex(&bytes))
    }

    fn validate(&self) -> Result<(), NativeError> {
        self.request.validate()?;
        self.proposed_job.validate()?;
        self.envelope.validate_against_job(&self.proposed_job)?;
        if self.schema_version != 1
            || self.preview_digest != self.compute_digest()?
            || self.approval_subject_digest != self.envelope.approval_subject_digest
            || self.request.work_brief_digest != self.proposed_job.work_brief_digest
            || self.proposed_job.planning_result.as_ref() != Some(&self.request.planning_result)
        {
            return Err(invalid("Admission preview integrity mismatch"));
        }
        self.marker()?.validate_for_job(&self.proposed_job)
    }

    fn marker(&self) -> Result<AdmissionMarker, NativeError> {
        Ok(AdmissionMarker {
            schema_version: 1,
            request_key: self.request.request_key.clone(),
            request_digest: request_digest(&self.request)?,
            preview_digest: self.preview_digest.clone(),
            approval_subject_digest: self.approval_subject_digest.clone(),
            envelope_digest: self.envelope.envelope_digest.clone(),
            source_job_revision: self.request.binding.expected_job_revision,
            resulting_job_revision: self.proposed_job.job_revision,
            created_at_ms: self.request.execution.created_at_ms,
            executable_pins: self.executable_pins.clone(),
        })
    }
}

/// Immutable per-job marker. Stored in the same transaction as the approval linkage.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdmissionMarker {
    /// Supported marker schema (`1`).
    pub schema_version: u32,
    /// Original stable request key.
    pub request_key: String,
    /// Domain-separated normalized original request identity.
    pub request_digest: String,
    /// Confirmed admission consent subject.
    pub preview_digest: String,
    /// Confirmed exact authority subject.
    pub approval_subject_digest: String,
    /// Confirmed full execution envelope digest.
    pub envelope_digest: String,
    /// Original source job revision.
    pub source_job_revision: u64,
    /// Linked job revision; later progress may increase the live revision.
    pub resulting_job_revision: u64,
    /// Original timestamp; unchanged during reconciliation.
    pub created_at_ms: u64,
    /// Canonical Worker, Reviewer and Closure executable pins.
    pub executable_pins: AdmissionExecutablePins,
}

impl AdmissionMarker {
    /// Checks structural integrity and immutable linkage without imposing current readiness.
    pub fn validate_for_job(&self, job: &CoworkerJobRecord) -> Result<(), NativeError> {
        bounded(self)?;
        validate_bounded_identifier(
            &self.request_key,
            "admission.request_key",
            MAX_COWORKER_ID_LEN,
        )?;
        for digest in [
            &self.request_digest,
            &self.preview_digest,
            &self.approval_subject_digest,
            &self.envelope_digest,
        ] {
            threadlane_workers::validate_sha256_hex_digest(digest, "admission digest")
                .map_err(|_| invalid("Malformed admission digest"))?;
        }
        let linkage = job
            .approval_linkage
            .as_ref()
            .ok_or_else(|| invalid("Admission marker has no linkage"))?;
        if self.schema_version != 1
            || self.source_job_revision == 0
            || self.resulting_job_revision < self.source_job_revision
            || job.job_revision < self.resulting_job_revision
            || linkage.approval_subject_digest != self.approval_subject_digest
            || self.executable_pins.workers.len() != job.tasks.len()
        {
            return Err(invalid(
                "Admission marker does not match immutable job subjects",
            ));
        }
        for task in &job.tasks {
            let pin = self
                .executable_pins
                .workers
                .get(&task.task_id)
                .ok_or_else(|| invalid("Missing Worker pin"))?;
            if pin.choice != task.selected_choice || !pin.canonical_executable.is_absolute() {
                return Err(invalid("Worker pin does not match the frozen task choice"));
            }
        }
        for pin in [
            &self.executable_pins.reviewer,
            &self.executable_pins.closure,
        ] {
            if !pin.canonical_executable.is_absolute() {
                return Err(invalid("Missing canonical advisory executable pin"));
            }
        }
        Ok(())
    }
}

/// Explicit trusted-local human attestation. These flags do not change any subject digest.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdmissionConfirmation {
    /// Required trusted-local operator attestation; not evidence of native chat provenance.
    pub trusted_local_attested: bool,
    /// Exact admission preview digest shown to the human.
    pub preview_digest: String,
    /// Exact existing approval subject digest shown to the human.
    pub approval_subject_digest: String,
    /// Exact full envelope digest shown to the human.
    pub envelope_digest: String,
}

/// Proven progress through separate persistence boundaries; never an execution receipt.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AdmissionStage {
    /// Original consent persisted before workflow binding.
    Intent,
    /// Linkage and marker durably recorded together.
    Linked,
    /// Controller runtime durably initialized with the exact frozen envelope.
    RuntimeRecorded,
    /// All persistence succeeded; read-only proof additionally requires a durability witness.
    Complete,
    /// A post-rename boundary failed; explicit reconciliation is mandatory.
    Uncertain,
}

/// Bounded private intent and subsequent admission receipt, preserving the original consent.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdmissionReceipt {
    /// Supported receipt schema (`1`).
    pub schema_version: u32,
    /// Original complete frozen consent subject.
    pub preview: AdmissionPreview,
    /// Original trusted-local confirmation; reconciliation may not replace it.
    pub confirmation: AdmissionConfirmation,
    /// Last persistence stage; does not describe provider execution.
    pub stage: AdmissionStage,
    /// Monotonic evidence that runtime persistence succeeded. A disappeared runtime must never
    /// be recreated with fresh counters after this becomes true, including uncertain receipts.
    pub runtime_initialized: bool,
}

impl AdmissionReceipt {
    fn validate(&self) -> Result<(), NativeError> {
        bounded(self)?;
        self.preview.validate()?;
        if self.schema_version != 1 {
            return Err(invalid("Unsupported admission receipt schema"));
        }
        if matches!(
            self.stage,
            AdmissionStage::RuntimeRecorded | AdmissionStage::Complete
        ) && !self.runtime_initialized
        {
            return Err(invalid(
                "Admission receipt lost its runtime persistence evidence",
            ));
        }
        confirm(&self.preview, &self.confirmation)
    }
}

/// Independent read-only classification of intent, linkage and runtime.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AdmissionInspectionState {
    /// No intent or marker exists; may be an unadmitted or historical/manual job.
    Absent,
    /// A valid original intent exists and one or more admission writes are missing.
    PartiallyRecorded,
    /// Exact linkage/runtime, final receipt and successful durability witness all match.
    Complete,
    /// Independent persistent subjects conflict or a mandatory receipt disappeared.
    Conflicting,
    /// Explicitly Uncertain persistence requires reconciliation. A Complete receipt without a
    /// process-local witness can instead establish durability at a deliberate execution boundary;
    /// inspection reports this uncertainty without acquiring a lock or syncing.
    Uncertain,
}

/// Read-only independent observations; does not make an execution eligibility claim.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct AdmissionInspection {
    /// Independent classification.
    pub state: AdmissionInspectionState,
    /// Whether a validated original intent exists.
    pub intent_present: bool,
    /// Whether the immutable marker and linkage match the original subject.
    pub linkage_present: bool,
    /// Whether the controller runtime envelope matches the original subject.
    pub runtime_present: bool,
    /// Validated receipt when present. Corruption returns an error instead of repairing data.
    pub receipt: Option<AdmissionReceipt>,
}

/// Native admission service. Construction validates existing directories and never initializes them.
#[derive(Debug, Clone)]
pub struct CoworkerAdmissionService {
    workflow: CoworkerWorkflowStore,
    controller: ControllerPolicyStore,
    authority_dir: PathBuf,
    registry_dir: PathBuf,
    failure_probe: Option<fn(AdmissionPersistenceBoundary) -> Result<(), NativeError>>,
}

/// Persistence boundary instrumentation for deterministic failure/recovery qualification.
/// A probe may refuse progress but can never authorize any execution effect.
#[doc(hidden)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AdmissionPersistenceBoundary {
    /// Before the original intent is persisted.
    BeforeIntent,
    /// After intent persistence, before any linkage.
    AfterIntent,
    /// Before the atomic marker/linkage workflow transaction.
    BeforeLinkage,
    /// After workflow durability, before receipt advancement.
    AfterLinkage,
    /// Before runtime initialization.
    BeforeRuntime,
    /// After runtime durability, before receipt advancement.
    AfterRuntime,
    /// Before final receipt persistence.
    BeforeComplete,
    /// After final visible receipt persistence, before establishing a successful witness.
    AfterComplete,
}

impl CoworkerAdmissionService {
    /// Opens existing private stores without creating directories, locks or runtime state.
    pub fn new(
        plans_dir: &Path,
        authority_dir: &Path,
        registry_dir: &Path,
    ) -> Result<Self, NativeError> {
        for (path, label) in [
            (plans_dir, "plans directory"),
            (authority_dir, "authority directory"),
            (registry_dir, "registry directory"),
        ] {
            validate_absolute_no_symlink_components(path, label)?;
        }
        if authority_dir.starts_with(plans_dir)
            || plans_dir.starts_with(authority_dir)
            || authority_dir.starts_with(registry_dir)
            || registry_dir.starts_with(authority_dir)
        {
            return Err(invalid(
                "Authority directory must remain separate from plans and registry",
            ));
        }
        let workflow = CoworkerWorkflowStore::new(plans_dir)?;
        let controller = ControllerPolicyStore::new(plans_dir)?;
        // Use the shared bounded private readers, never AuthorityStore::open/get_for_operator.
        AuthorityStore::read_snapshot_readonly_at(authority_dir)
            .map_err(|_| invalid("Cannot read authority snapshot"))?;
        RegistryStore::read_snapshot_readonly_at(registry_dir)
            .map_err(|_| invalid("Cannot read registry snapshot"))?;
        PlanStore::read_snapshot_readonly_at(plans_dir)
            .map_err(|_| invalid("Cannot read plan snapshot"))?;
        Ok(Self {
            workflow,
            controller,
            authority_dir: authority_dir.to_path_buf(),
            registry_dir: registry_dir.to_path_buf(),
            failure_probe: None,
        })
    }

    /// Installs trusted Rust-only persistence failure instrumentation. Probes must not reenter
    /// admission or workflow/controller stores while the admission lock is held.
    #[doc(hidden)]
    pub fn with_failure_probe(
        mut self,
        probe: fn(AdmissionPersistenceBoundary) -> Result<(), NativeError>,
    ) -> Self {
        self.failure_probe = Some(probe);
        self
    }

    fn probe(&self, boundary: AdmissionPersistenceBoundary) -> Result<(), NativeError> {
        match self.failure_probe {
            Some(probe) => probe(boundary),
            None => Ok(()),
        }
    }

    /// Constructs the prospective linked job and exact execution envelope entirely in memory.
    pub fn preview(&self, request: &AdmissionRequest) -> Result<AdmissionPreview, NativeError> {
        request.validate()?;
        let request = request.normalized();
        let b = &request.binding;
        let mut ledger = self.workflow.read_binding_ledger(&b.binding_id)?;
        if Some(ledger.ledger_revision) != b.expected_ledger_revision {
            return Err(invalid("Admission source ledger revision changed"));
        }
        let source = ledger
            .jobs
            .iter()
            .find(|j| j.job_id == b.job_id)
            .ok_or_else(|| invalid("Admission job is absent"))?;
        if source.job_revision != b.expected_job_revision
            || source.work_brief_digest != request.work_brief_digest
            || source.planning_result.as_ref() != Some(&request.planning_result)
            || source.binding_id != b.binding_id
            || source.thread_uuid != b.thread_uuid
            || source.holds.iter().any(|h| h.active)
            || !source
                .work_brief
                .is_ready_for_execution_approval_with_planning(source.planning_result.as_ref())
        {
            return Err(invalid(
                "Admission job, planning result, brief, readiness or source revision changed",
            ));
        }
        if !b.task_interfaces.is_empty()
            && b.task_interfaces != request.planning_result.task_interfaces
        {
            return Err(invalid(
                "Caller interfaces differ from the recorded planning result",
            ));
        }
        if ledger.admission_markers.contains_key(&b.job_id) {
            return Err(invalid(
                "Automatic admission already exists; inspect or record the original request",
            ));
        }
        let approval =
            AuthorityStore::get_for_operator_readonly_at(&self.authority_dir, &b.approval_id)
                .map_err(|_| invalid("Exact existing authority approval is absent or invalid"))?;
        let planning = &request.planning_result;
        if approval.plan_id != planning.plan_id
            || approval.plan_revision != planning.plan_revision
            || approval.plan_digest != planning.plan_digest
            || approval.profile_id != planning.profile_id
            || approval.registry_revision != planning.registry_revision
        {
            return Err(invalid(
                "Approval differs from the current published planning result",
            ));
        }
        let registry = RegistryStore::read_snapshot_readonly_at(&self.registry_dir)
            .map_err(|_| invalid("Cannot read registry snapshot"))?;
        let plans = PlanStore::read_snapshot_readonly_at(self.workflow.plans_dir())
            .map_err(|_| invalid("Cannot read plan snapshot"))?;
        let plan = plans
            .iter()
            .find(|p| p.plan_id == approval.plan_id && p.revision == approval.plan_revision)
            .ok_or_else(|| invalid("Approved plan is absent"))?;
        let compiled = compile_plan_revision(plan, &registry)
            .map_err(|_| invalid("Cannot compile exact published plan"))?;
        if compiled.plan_digest != approval.plan_digest || plan.binding_id != b.binding_id {
            return Err(invalid("Exact plan compilation or binding drifted"));
        }
        let outcome = prepare_job_approval_in_ledger(&mut ledger, b, &approval, &registry, &plans)?;
        let (proposed_job, changed) = match outcome {
            CoworkerLedgerMutationOutcome::Mutated(job) => (job, true),
            CoworkerLedgerMutationOutcome::IdempotentExisting(job) => (job, false),
        };
        // Already manually bound jobs may opt in only with the exact immutable task linkage.
        // Preparation preserves existing mutable task evidence; it never replaces task records.
        for task in &proposed_job.tasks {
            let approved = approval
                .tasks
                .iter()
                .find(|t| t.task_id == task.task_id)
                .ok_or_else(|| invalid("Unapproved task"))?;
            let resolved = preflight(
                &registry,
                &PreflightRequest {
                    profile_id: Some(approval.profile_id.clone()),
                    roles: vec![RolePreflightRequest::new(task.role, Some(task.difficulty))],
                },
                &b.policy,
            )?;
            let resolved_choice = resolved
                .roles
                .first()
                .and_then(|r| r.selected.as_ref())
                .ok_or_else(|| invalid("Missing exact resolved Worker choice"))?;
            if !resolved.ready
                || crate::profile_flow::normalize_coder_choice(resolved_choice)?
                    != task.selected_choice
            {
                return Err(invalid(
                    "Bound Worker choice differs from exact profile/difficulty resolution",
                ));
            }
            let interfaces = request
                .planning_result
                .task_interfaces
                .get(&task.task_id)
                .cloned()
                .unwrap_or_default();
            if task.task_digest != approved.task_digest
                || task.depends_on != approved.depends_on
                || task.write_paths != approved.allowed_write_paths
                || task.owned_interfaces != interfaces.owned_interfaces
                || task.consumed_interfaces != interfaces.consumed_interfaces
                || task.role != approved.role
                || task.difficulty != approved.difficulty
                || task.selected_choice.tool_id != approved.tool_id
                || task.selected_choice.adapter != approved.adapter
                || task.selected_choice.model_id != approved.model_id
                || task.selected_choice.model_arg != approved.model_arg
                || task.selected_choice.effort != approved.effort
            {
                return Err(invalid(
                    "Bound task identity, dependency, scope or interfaces drifted",
                ));
            }
        }
        let mut pins = BTreeMap::new();
        for task in &proposed_job.tasks {
            let approved = approval
                .tasks
                .iter()
                .find(|t| t.task_id == task.task_id)
                .ok_or_else(|| invalid("Unapproved task"))?;
            let path = approved
                .canonical_executable
                .clone()
                .ok_or_else(|| invalid("Approved Worker has no canonical executable pin"))?;
            let pin = AdmissionExecutablePin {
                choice: task.selected_choice.clone(),
                canonical_executable: path,
            };
            pin.executable()?;
            let tool = registry
                .tools
                .iter()
                .find(|t| t.id == pin.choice.tool_id)
                .ok_or_else(|| invalid("Worker tool is absent"))?;
            if resolve_advisory_tool_executable(tool)? != pin.canonical_executable {
                return Err(invalid("Worker executable drifted from authority pin"));
            }
            pins.insert(task.task_id.clone(), pin);
        }
        let resolve_role = |role,
                            difficulty,
                            supplied: &SelectedRoleChoice|
         -> Result<AdmissionExecutablePin, NativeError> {
            let report = preflight(
                &registry,
                &PreflightRequest {
                    profile_id: Some(approval.profile_id.clone()),
                    roles: vec![RolePreflightRequest::new(role, difficulty)],
                },
                &b.policy,
            )?;
            if !report.ready {
                return Err(invalid("Advisory role preflight refused admission"));
            }
            let selected = report
                .roles
                .first()
                .and_then(|r| r.selected.as_ref())
                .ok_or_else(|| invalid("Missing resolved advisory choice"))?;
            let selected = normalize_read_only_advisory_choice(role, selected)?;
            if normalize_read_only_advisory_choice(role, supplied)? != selected {
                return Err(invalid(
                    "Caller choice differs from the exact resolved profile and difficulty",
                ));
            }
            let tool = registry
                .tools
                .iter()
                .find(|t| t.id == selected.tool_id)
                .ok_or_else(|| invalid("Advisory tool is absent"))?;
            Ok(AdmissionExecutablePin {
                choice: selected,
                canonical_executable: resolve_advisory_tool_executable(tool)?,
            })
        };
        let executable_pins = AdmissionExecutablePins {
            workers: pins,
            reviewer: resolve_role(
                WorkflowRole::Reviewer,
                request.reviewer_difficulty,
                &request.execution.reviewer_choice,
            )?,
            closure: resolve_role(
                WorkflowRole::Closure,
                request.closure_difficulty,
                &request.execution.closure_choice,
            )?,
        };
        let mut execution = request.execution.clone();
        execution.expected_job_revision = proposed_job.job_revision;
        let envelope =
            ControllerPolicyStore::prepare_execution_envelope(&execution, &proposed_job)?.envelope;
        let coder_budget = envelope.coder_budget()?;
        if approval.budgets.timeout_ms > coder_budget.max_timeout_ms_per_call
            || approval.budgets.max_stdout_bytes > coder_budget.max_stdout_bytes_per_call
            || approval.budgets.max_stderr_bytes > coder_budget.max_stderr_bytes_per_call
        {
            return Err(invalid(
                "Authority Worker budgets exceed the frozen Coder role budget",
            ));
        }
        if let Some(runtime) = self
            .controller
            .get_job_runtime_readonly(&b.binding_id, &b.job_id)?
        {
            if !same_envelope(&runtime.envelope, &envelope) {
                return Err(invalid(
                    "Existing controller envelope differs from admission",
                ));
            }
        }
        let resulting_ledger_revision = ledger
            .ledger_revision
            .checked_add(1)
            .ok_or_else(|| invalid("Ledger revision overflow"))?;
        // Even an existing matching manual linkage receives the marker in a new ledger transaction.
        let _ = changed;
        let planning_authority = ledger
            .planning_grants
            .iter()
            .find(|g| g.grant_id == request.planning_result.grant_id)
            .cloned()
            .ok_or_else(|| invalid("Recorded planning authority is absent"))?;
        let planning_profile = registry
            .profiles
            .iter()
            .find(|p| p.id == approval.profile_id)
            .cloned()
            .ok_or_else(|| invalid("Planning profile disappeared"))?;
        let mut planning_roles: Vec<_> = planning_profile
            .execution_assignments()
            .filter(|a| matches!(a.role, WorkflowRole::Orchestrator | WorkflowRole::Architect))
            .map(|a| RolePreflightRequest::new(a.role, a.difficulty))
            .collect();
        for role in [WorkflowRole::Orchestrator, WorkflowRole::Architect] {
            if !planning_roles.iter().any(|r| r.role == role) {
                planning_roles.push(RolePreflightRequest::new(role, None));
            }
        }
        let planning_configuration = preflight(
            &registry,
            &PreflightRequest {
                profile_id: Some(approval.profile_id.clone()),
                roles: planning_roles,
            },
            &planning_authority.policy,
        )?;
        let planning_models: Vec<_> = registry
            .models
            .iter()
            .filter(|m| {
                planning_profile.assignments.iter().any(|a| {
                    matches!(a.role, WorkflowRole::Orchestrator | WorkflowRole::Architect)
                        && a.choice.model_id == m.id
                })
            })
            .cloned()
            .collect();
        let planning_tools = registry
            .tools
            .iter()
            .filter(|t| planning_models.iter().any(|m| m.tool_id == t.id))
            .cloned()
            .collect();
        let mut preview = AdmissionPreview {
            schema_version: 1,
            request,
            resulting_ledger_revision,
            proposed_job,
            approval_subject_digest: approval.subject_digest,
            max_parallel: approval.max_parallel,
            authority_budgets: approval.budgets,
            envelope,
            executable_pins,
            planning_configuration,
            planning_profile,
            planning_models,
            planning_tools,
            planning_authority,
            coworker_configuration: "human_selected_native_conversation_no_profile_execution_slot"
                .into(),
            preview_digest: String::new(),
        };
        preview.preview_digest = preview.compute_digest()?;
        preview.validate()?;
        Ok(preview)
    }

    /// Recomputes consent before any persistence. Identical completed duplicates are true no-ops.
    pub fn record(
        &self,
        request: &AdmissionRequest,
        confirmation: &AdmissionConfirmation,
    ) -> Result<AdmissionReceipt, NativeError> {
        request.validate()?;
        let b = &request.binding;
        // A proven completed duplicate takes no lock and performs no writes, even after job progress.
        if let Some(receipt) = read_receipt(&self.workflow, &b.binding_id, &b.job_id)? {
            ensure_duplicate(&receipt, request, confirmation)?;
            let inspection = self.inspect(&b.binding_id, &b.job_id)?;
            if receipt.stage == AdmissionStage::Complete
                && inspection.linkage_present
                && inspection.runtime_present
                && inspection.state == AdmissionInspectionState::Complete
            {
                return Ok(receipt);
            }
            // A fresh process has no successful-sync witness. Establish it only after
            // acquiring the admission lock and rereading the unchanged receipt below.
        } else {
            // Verify consent before even creating the admission lockfile. Repeat under that
            // lock below; another identical recorder may finish while preparation is reading.
            match self.preview(request) {
                Ok(preview) => confirm(&preview, confirmation)?,
                Err(error) => {
                    let Some(receipt) = read_receipt(&self.workflow, &b.binding_id, &b.job_id)?
                    else {
                        return Err(error);
                    };
                    ensure_duplicate(&receipt, request, confirmation)?;
                }
            }
        }
        let _guard = acquire_cross_process_lock(
            self.workflow.plans_dir(),
            &lock_name(&b.binding_id, &b.job_id),
            "admission lock",
        )?;
        if let Some(receipt) = read_receipt(&self.workflow, &b.binding_id, &b.job_id)? {
            ensure_duplicate(&receipt, request, confirmation)?;
            let inspection = self.inspect(&b.binding_id, &b.job_id)?;
            if receipt.stage == AdmissionStage::Complete
                && inspection.linkage_present
                && inspection.runtime_present
                && inspection.state != AdmissionInspectionState::Conflicting
            {
                establish_complete_locked(&self.workflow, &self.controller, &receipt)?;
                return Ok(receipt);
            }
            return Err(invalid(
                "An admission intent already exists; inspect and explicitly reconcile it",
            ));
        }
        let preview = self.preview(request)?;
        confirm(&preview, confirmation)?;
        let mut receipt = AdmissionReceipt {
            schema_version: 1,
            preview,
            confirmation: confirmation.clone(),
            stage: AdmissionStage::Intent,
            runtime_initialized: false,
        };
        self.probe(AdmissionPersistenceBoundary::BeforeIntent)?;
        if let Err(error) = self
            .persist(&receipt)
            .and_then(|_| self.probe(AdmissionPersistenceBoundary::AfterIntent))
        {
            if error.error_code() == NativeErrorCode::PersistenceUncertain {
                receipt.stage = AdmissionStage::Uncertain;
                let _ = self.persist(&receipt);
            }
            return Err(error);
        }
        self.finish(&mut receipt, false)
    }

    /// Reads intent, immutable marker/linkage and controller runtime independently without locks.
    pub fn inspect(
        &self,
        binding_id: &str,
        job_id: &str,
    ) -> Result<AdmissionInspection, NativeError> {
        inspect_admission(&self.workflow, &self.controller, binding_id, job_id)
    }

    /// Completes only missing admission writes backed by the original recorded human consent.
    /// Never starts a host, provider, check, commit, integration, task or lease.
    pub fn reconcile(
        &self,
        binding_id: &str,
        job_id: &str,
    ) -> Result<AdmissionReceipt, NativeError> {
        validate_bounded_identifier(binding_id, "binding_id", MAX_COWORKER_ID_LEN)?;
        validate_bounded_identifier(job_id, "job_id", MAX_COWORKER_ID_LEN)?;
        let _guard = acquire_cross_process_lock(
            self.workflow.plans_dir(),
            &lock_name(binding_id, job_id),
            "admission lock",
        )?;
        let inspection = self.inspect(binding_id, job_id)?;
        if inspection.state == AdmissionInspectionState::Conflicting {
            return Err(invalid(
                "Conflicting admission subjects cannot be reconciled",
            ));
        }
        let mut receipt = inspection
            .receipt
            .ok_or_else(|| invalid("No original admission consent to reconcile"))?;
        if receipt.stage == AdmissionStage::Complete
            && inspection.linkage_present
            && inspection.runtime_present
        {
            establish_complete_locked(&self.workflow, &self.controller, &receipt)?;
            return Ok(receipt);
        }
        self.finish(&mut receipt, true)
    }

    fn finish(
        &self,
        receipt: &mut AdmissionReceipt,
        reconcile: bool,
    ) -> Result<AdmissionReceipt, NativeError> {
        receipt.validate()?;
        let result = self.finish_inner(receipt, reconcile);
        if let Err(ref error) = result {
            if error.error_code() == NativeErrorCode::PersistenceUncertain {
                forget_witness(&receipt_path(
                    &self.workflow,
                    &receipt.preview.request.binding.binding_id,
                    &receipt.preview.request.binding.job_id,
                )?);
                receipt.stage = AdmissionStage::Uncertain;
                // Best effort diagnostic only. A failed write never establishes a witness.
                let _ = self.persist(receipt);
            }
        }
        result
    }

    fn finish_inner(
        &self,
        receipt: &mut AdmissionReceipt,
        reconcile: bool,
    ) -> Result<AdmissionReceipt, NativeError> {
        let b = &receipt.preview.request.binding;
        let inspection = self.inspect(&b.binding_id, &b.job_id)?;
        if inspection.state == AdmissionInspectionState::Conflicting {
            return Err(invalid("Admission subjects conflict"));
        }
        if !inspection.linkage_present {
            // Recompute the original source tuple before the first missing write. Never refresh it.
            let current = self.preview(&receipt.preview.request)?;
            if current != receipt.preview {
                return Err(invalid("Original admission subject drifted before linkage"));
            }
            let marker = receipt.preview.marker()?;
            let proposed = receipt.preview.proposed_job.clone();
            self.probe(AdmissionPersistenceBoundary::BeforeLinkage)?;
            self.workflow.transact_binding_ledger(
                &b.binding_id,
                b.expected_ledger_revision,
                |ledger| {
                    ledger.ensure_thread_scope(&b.thread_uuid)?;
                    if ledger.admission_markers.contains_key(&b.job_id) {
                        return Err(invalid("Admission marker appeared concurrently"));
                    }
                    if ledger
                        .jobs
                        .iter()
                        .any(|j| j.supersedes_job_id.as_deref() == Some(b.job_id.as_str()))
                    {
                        return Err(invalid("Admission job was superseded"));
                    }
                    let job = ledger
                        .jobs
                        .iter_mut()
                        .find(|j| j.job_id == b.job_id)
                        .ok_or_else(|| invalid("Admission job disappeared"))?;
                    if job.job_revision != b.expected_job_revision
                        || job.work_brief_digest != b_work_brief(receipt)
                        || job.planning_result.as_ref()
                            != Some(&receipt.preview.request.planning_result)
                        || job.holds.iter().any(|h| h.active)
                    {
                        return Err(invalid("Source job changed before linkage persistence"));
                    }
                    if job.approval_linkage.is_some() && job != &proposed {
                        return Err(invalid(
                            "Existing linked job differs from the consented candidate",
                        ));
                    }
                    *job = proposed.clone();
                    ledger.admission_markers.insert(b.job_id.clone(), marker);
                    Ok(CoworkerLedgerMutationOutcome::Mutated(()))
                },
            )?;
            self.probe(AdmissionPersistenceBoundary::AfterLinkage)?;
            receipt.stage = AdmissionStage::Linked;
            self.persist(receipt)?;
        }
        let ledger = self.workflow.read_binding_ledger(&b.binding_id)?;
        let job = ledger
            .jobs
            .iter()
            .find(|j| j.job_id == b.job_id)
            .ok_or_else(|| invalid("Linked admission job disappeared"))?;
        if ledger.admission_markers.get(&b.job_id) != Some(&receipt.preview.marker()?) {
            return Err(invalid("Immutable admission marker changed"));
        }
        if self
            .controller
            .get_job_runtime_readonly(&b.binding_id, &b.job_id)?
            .is_none()
        {
            // Missing runtime may only be initialized for the original, unadvanced job.
            if job != &receipt.preview.proposed_job {
                return Err(invalid(
                    "Job advanced without admission runtime; cannot initialize fresh counters",
                ));
            }
            let mut envelope = receipt.preview.envelope.clone();
            envelope.operator_attested = true;
            self.probe(AdmissionPersistenceBoundary::BeforeRuntime)?;
            self.controller.record_admission_envelope(&envelope, job)?;
            receipt.runtime_initialized = true;
            self.probe(AdmissionPersistenceBoundary::AfterRuntime)?;
            receipt.stage = AdmissionStage::RuntimeRecorded;
            self.persist(receipt)?;
        }
        let inspection = self.inspect(&b.binding_id, &b.job_id)?;
        if !inspection.linkage_present
            || !inspection.runtime_present
            || inspection.state == AdmissionInspectionState::Conflicting
        {
            return Err(invalid(
                "Independent admission persistence did not match original subjects",
            ));
        }
        receipt.runtime_initialized = true;
        if reconcile {
            // Explicitly establish durability of visible original writes. Do not rewrite ledgers.
            for path in [
                self.workflow.ledger_path_for_binding(&b.binding_id)?,
                self.controller.ledger_path_for_binding(&b.binding_id)?,
                receipt_path(&self.workflow, &b.binding_id, &b.job_id)?,
            ] {
                sync_existing(&path)?;
            }
            sync_existing(self.workflow.plans_dir())?;
        }
        self.probe(AdmissionPersistenceBoundary::BeforeComplete)?;
        receipt.stage = AdmissionStage::Complete;
        self.persist(receipt)?;
        self.probe(AdmissionPersistenceBoundary::AfterComplete)?;
        remember_witness(
            receipt_path(&self.workflow, &b.binding_id, &b.job_id)?,
            receipt,
        )?;
        Ok(receipt.clone())
    }

    fn persist(&self, receipt: &AdmissionReceipt) -> Result<(), NativeError> {
        receipt.validate()?;
        let b = &receipt.preview.request.binding;
        write_private_file_atomic(
            self.workflow.plans_dir(),
            &receipt_name(&b.binding_id, &b.job_id),
            &bounded(receipt)?,
            "admission receipt",
        )?;
        Ok(())
    }
}

/// Admission proof for deliberate effectful boundaries. Legacy jobs pass through unchanged.
/// A Complete unchanged receipt may establish durability by syncing existing files without
/// changing bytes, mtime, counters or leases. Partial/conflicting/explicitly Uncertain receipts
/// require explicit reconciliation. Never use this function in pure preview or status.
pub fn verify_complete_admission(
    workflow: &CoworkerWorkflowStore,
    controller: &ControllerPolicyStore,
    job: &CoworkerJobRecord,
) -> Result<(), NativeError> {
    let mut inspection = inspect_admission(workflow, controller, &job.binding_id, &job.job_id)?;
    if inspection.state == AdmissionInspectionState::Uncertain
        && inspection
            .receipt
            .as_ref()
            .is_some_and(|r| r.stage == AdmissionStage::Complete)
    {
        let _guard = acquire_cross_process_lock(
            workflow.plans_dir(),
            &lock_name(&job.binding_id, &job.job_id),
            "admission lock",
        )?;
        let current = inspect_admission(workflow, controller, &job.binding_id, &job.job_id)?;
        let receipt = current
            .receipt
            .as_ref()
            .ok_or_else(|| invalid("Admission receipt disappeared"))?;
        establish_complete_locked(workflow, controller, receipt)?;
        inspection = inspect_admission(workflow, controller, &job.binding_id, &job.job_id)?;
    }
    match inspection.state {
        AdmissionInspectionState::Absent => Ok(()),
        AdmissionInspectionState::Complete => {
            let receipt = inspection
                .receipt
                .ok_or_else(|| invalid("Missing complete admission receipt"))?;
            receipt.preview.marker()?.validate_for_job(job)?;
            receipt.preview.envelope.validate_against_job(job)
        }
        AdmissionInspectionState::Uncertain => Err(NativeError::persistence_uncertain(
            "Admission durability requires explicit reconciliation",
        )),
        _ => Err(invalid(
            "Automatic admission is incomplete or conflicting; execution is forbidden",
        )),
    }
}

/// Returns exact frozen executable pins only after the complete-admission proof succeeds.
/// Manual jobs return `None`; a marked job never falls back to live resolution.
pub fn complete_admission_pins(
    workflow: &CoworkerWorkflowStore,
    controller: &ControllerPolicyStore,
    job: &CoworkerJobRecord,
) -> Result<Option<AdmissionExecutablePins>, NativeError> {
    verify_complete_admission(workflow, controller, job)?;
    let pins = workflow
        .read_binding_ledger(&job.binding_id)?
        .admission_markers
        .get(&job.job_id)
        .map(|m| m.executable_pins.clone());
    if let Some(pins) = &pins {
        pins.reviewer.executable()?;
        pins.closure.executable()?;
        for pin in pins.workers.values() {
            pin.executable()?;
        }
    }
    Ok(pins)
}

// Caller holds the admission lock. Successful sync returns, not visible bytes, establish
// the witness. No missing file is created and no intent stage is advanced.
fn establish_complete_locked(
    workflow: &CoworkerWorkflowStore,
    controller: &ControllerPolicyStore,
    receipt: &AdmissionReceipt,
) -> Result<(), NativeError> {
    let b = &receipt.preview.request.binding;
    let check = inspect_admission(workflow, controller, &b.binding_id, &b.job_id)?;
    if receipt.stage != AdmissionStage::Complete
        || !receipt.runtime_initialized
        || !check.linkage_present
        || !check.runtime_present
        || check.state == AdmissionInspectionState::Conflicting
        || check.receipt.as_ref() != Some(receipt)
    {
        return Err(invalid(
            "Only unchanged complete admission can be witnessed at execution",
        ));
    }
    if check.state == AdmissionInspectionState::Complete {
        return Ok(());
    }
    let path = receipt_path(workflow, &b.binding_id, &b.job_id)?;
    forget_witness(&path);
    for existing in [
        workflow.ledger_path_for_binding(&b.binding_id)?,
        controller.ledger_path_for_binding(&b.binding_id)?,
        path.clone(),
    ] {
        validate_absolute_no_symlink_components(&existing, "admission persistence")?;
        sync_existing(&existing)?;
    }
    sync_existing(workflow.plans_dir())?;
    let after = inspect_admission(workflow, controller, &b.binding_id, &b.job_id)?;
    if after.receipt.as_ref() != Some(receipt)
        || !after.linkage_present
        || !after.runtime_present
        || after.state == AdmissionInspectionState::Conflicting
    {
        return Err(invalid("Admission changed during durability establishment"));
    }
    remember_witness(path, receipt)
}

fn inspect_admission(
    workflow: &CoworkerWorkflowStore,
    controller: &ControllerPolicyStore,
    binding_id: &str,
    job_id: &str,
) -> Result<AdmissionInspection, NativeError> {
    validate_bounded_identifier(job_id, "job_id", MAX_COWORKER_ID_LEN)?;
    let ledger = workflow.read_binding_ledger(binding_id)?;
    let receipt = read_receipt(workflow, binding_id, job_id)?;
    let marker = ledger.admission_markers.get(job_id);
    let runtime = controller.get_job_runtime_readonly(binding_id, job_id)?;
    let mut inspection = AdmissionInspection {
        state: AdmissionInspectionState::Absent,
        intent_present: receipt.is_some(),
        linkage_present: false,
        runtime_present: false,
        receipt: receipt.clone(),
    };
    let Some(receipt) = receipt else {
        if marker.is_some() {
            inspection.state = AdmissionInspectionState::Conflicting;
        }
        return Ok(inspection);
    };
    let preview = &receipt.preview;
    let job = ledger.jobs.iter().find(|j| j.job_id == job_id);
    let linkage_matches = job.is_some_and(|job| {
        job.approval_linkage == preview.proposed_job.approval_linkage
            && job.work_brief_digest == preview.proposed_job.work_brief_digest
            && job.planning_result == preview.proposed_job.planning_result
    });
    let expected_marker = preview.marker()?;
    inspection.linkage_present = linkage_matches && marker == Some(&expected_marker);
    inspection.runtime_present = runtime.as_ref().is_some_and(|r| {
        same_envelope(&r.envelope, &preview.envelope) && r.envelope.operator_attested
    });
    let conflicting = job.is_none()
        || marker.is_some_and(|m| m != &expected_marker)
        || (marker.is_some() && !linkage_matches)
        || (runtime.is_some() && !inspection.runtime_present)
        || (receipt.runtime_initialized && runtime.is_none())
        || (matches!(
            receipt.stage,
            AdmissionStage::Linked | AdmissionStage::RuntimeRecorded | AdmissionStage::Complete
        ) && !inspection.linkage_present)
        || job.is_some_and(|j| j.approval_linkage.is_some() && !linkage_matches);
    inspection.state = if conflicting {
        AdmissionInspectionState::Conflicting
    } else if receipt.stage == AdmissionStage::Uncertain {
        AdmissionInspectionState::Uncertain
    } else if inspection.linkage_present
        && inspection.runtime_present
        && receipt.stage == AdmissionStage::Complete
    {
        if has_witness(&receipt_path(workflow, binding_id, job_id)?, &receipt)? {
            AdmissionInspectionState::Complete
        } else {
            AdmissionInspectionState::Uncertain
        }
    } else {
        AdmissionInspectionState::PartiallyRecorded
    };
    Ok(inspection)
}

fn confirm(
    preview: &AdmissionPreview,
    confirmation: &AdmissionConfirmation,
) -> Result<(), NativeError> {
    if !confirmation.trusted_local_attested
        || confirmation.preview_digest != preview.preview_digest
        || confirmation.approval_subject_digest != preview.approval_subject_digest
        || confirmation.envelope_digest != preview.envelope.envelope_digest
    {
        return Err(NativeError::new(
            NativeErrorCode::UnauthorizedOperator,
            "Explicit confirmation of all three original admission subjects is required",
        ));
    }
    Ok(())
}

fn ensure_duplicate(
    receipt: &AdmissionReceipt,
    request: &AdmissionRequest,
    confirmation: &AdmissionConfirmation,
) -> Result<(), NativeError> {
    if receipt.preview.request != request.normalized() {
        return Err(invalid(
            "Conflicting reuse of admission job or request identity",
        ));
    }
    confirm(&receipt.preview, confirmation)
}

fn request_digest(request: &AdmissionRequest) -> Result<String, NativeError> {
    Ok(sha256_hex(&bounded(&(
        "threadlane-native:coworker-admission-request:v1",
        request.normalized(),
    ))?))
}

fn read_receipt(
    workflow: &CoworkerWorkflowStore,
    binding_id: &str,
    job_id: &str,
) -> Result<Option<AdmissionReceipt>, NativeError> {
    validate_bounded_identifier(binding_id, "binding_id", MAX_COWORKER_ID_LEN)?;
    validate_bounded_identifier(job_id, "job_id", MAX_COWORKER_ID_LEN)?;
    let path = receipt_path(workflow, binding_id, job_id)?;
    let Some(bytes) =
        read_private_file_bounded(&path, MAX_PRIVATE_STATE_FILE_BYTES, "admission receipt")?
    else {
        return Ok(None);
    };
    let receipt: AdmissionReceipt =
        serde_json::from_slice(&bytes).map_err(|_| invalid("Malformed admission receipt"))?;
    receipt.validate()?;
    let b = &receipt.preview.request.binding;
    if b.binding_id != binding_id || b.job_id != job_id {
        return Err(invalid("Admission receipt path scope mismatch"));
    }
    Ok(Some(receipt))
}

fn same_envelope(
    a: &FrozenControllerExecutionEnvelope,
    b: &FrozenControllerExecutionEnvelope,
) -> bool {
    let mut a = a.clone();
    let mut b = b.clone();
    a.operator_attested = false;
    b.operator_attested = false;
    a == b
}

fn tag(binding_id: &str, job_id: &str) -> String {
    let seed = format!(
        "threadlane-native:admission-path:v1:{}:{binding_id}:{job_id}",
        binding_id.len()
    );
    sha256_hex(seed.as_bytes())
}
fn receipt_name(binding_id: &str, job_id: &str) -> String {
    format!("coworker-admission-{}.json", tag(binding_id, job_id))
}
fn lock_name(binding_id: &str, job_id: &str) -> String {
    format!("coworker-admission-{}.lock", tag(binding_id, job_id))
}
fn receipt_path(
    workflow: &CoworkerWorkflowStore,
    binding_id: &str,
    job_id: &str,
) -> Result<PathBuf, NativeError> {
    validate_bounded_identifier(binding_id, "binding_id", MAX_COWORKER_ID_LEN)?;
    validate_bounded_identifier(job_id, "job_id", MAX_COWORKER_ID_LEN)?;
    Ok(workflow.plans_dir().join(receipt_name(binding_id, job_id)))
}
fn bounded<T: Serialize>(value: &T) -> Result<Vec<u8>, NativeError> {
    let bytes =
        serde_json::to_vec(value).map_err(|_| invalid("Cannot serialize admission subject"))?;
    if bytes.len() > MAX_PRIVATE_STATE_FILE_BYTES {
        return Err(invalid("Admission subject exceeds private byte bound"));
    }
    Ok(bytes)
}
fn invalid(message: &str) -> NativeError {
    NativeError::new(NativeErrorCode::ValidationFailed, message)
}
fn b_work_brief(receipt: &AdmissionReceipt) -> &str {
    &receipt.preview.request.work_brief_digest
}
fn sync_existing(path: &Path) -> Result<(), NativeError> {
    File::open(path).and_then(|f| f.sync_all()).map_err(|_| {
        NativeError::persistence_uncertain("Admission durability could not be established")
    })
}

// Bounded process-local witnesses cannot be recovered by interpreting visible bytes as a
// successful sync. A new process syncs Complete existing persistence at its effectful boundary;
// partial or explicitly Uncertain persistence requires explicit reconciliation.
static WITNESSES: OnceLock<Mutex<BTreeMap<PathBuf, String>>> = OnceLock::new();
fn witnesses() -> &'static Mutex<BTreeMap<PathBuf, String>> {
    WITNESSES.get_or_init(|| Mutex::new(BTreeMap::new()))
}
fn remember_witness(path: PathBuf, receipt: &AdmissionReceipt) -> Result<(), NativeError> {
    let digest = sha256_hex(&bounded(receipt)?);
    let mut map = witnesses()
        .lock()
        .map_err(|_| invalid("Admission witness lock poisoned"))?;
    if map.len() >= 1024 {
        map.clear();
    }
    map.insert(path, digest);
    Ok(())
}
fn has_witness(path: &Path, receipt: &AdmissionReceipt) -> Result<bool, NativeError> {
    Ok(witnesses()
        .lock()
        .map_err(|_| invalid("Admission witness lock poisoned"))?
        .get(path)
        == Some(&sha256_hex(&bounded(receipt)?)))
}
fn forget_witness(path: &Path) {
    if let Ok(mut map) = witnesses().lock() {
        map.remove(path);
    }
}
